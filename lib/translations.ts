// Utility functions for translations
export function getTranslation(locale: Locale, key: string): string {
  const translation = translations[locale];
  if (!translation) {
    console.warn(`Translation not found for locale: ${locale}`);
    return key;
  }

  // Check if the key exists directly in the translation object
  if (key in translation) {
    return translation[key] as string;
  }

  console.warn(`Translation key not found: ${key} for locale: ${locale}`);
  return key;
}

export function hasTranslation(locale: Locale, key: string): boolean {
  const translation = translations[locale];
  if (!translation) {
      return false;
  }
  
  return key in translation && typeof translation[key] === 'string';
}
